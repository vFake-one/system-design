"""
Experimental comparison on SYNTHETIC demonstration rows only.

Do not quote these numbers as real-world performance.
The Isolation Forest is not used to raise live alerts.
"""

import numpy as np
from sklearn.ensemble import IsolationForest

from app.services.risk_engine import score_from_features


FEATURE_ORDER = [
    "hours_overdue",
    "missed_7",
    "missed_14",
    "consecutive_misses",
    "days_since_visit",
    "hour_deviation",
]


def _row(hours_overdue, missed_7, missed_14, consecutive, days_visit, hour_dev):
    return {
        "hours_overdue": hours_overdue,
        "missed_7": missed_7,
        "missed_14": missed_14,
        "consecutive_misses": consecutive,
        "days_since_visit": days_visit,
        "hour_deviation": hour_dev,
        "needs_assistance": False,
    }


def synthetic_dataset(n_typical=80, n_unusual=20, seed=7):
    rng = np.random.default_rng(seed)
    rows = []
    # Typical contact pattern
    for _ in range(n_typical):
        rows.append(
            _row(
                hours_overdue=float(max(0, rng.normal(0.2, 0.4))),
                missed_7=int(rng.choice([0, 0, 0, 1])),
                missed_14=int(rng.choice([0, 0, 1, 1])),
                consecutive=int(rng.choice([0, 0, 0, 1])),
                days_visit=float(max(0.5, rng.normal(4, 2))),
                hour_dev=float(abs(rng.normal(0.5, 0.6))),
            )
        )
    # Unusual operational pattern (still synthetic)
    for _ in range(n_unusual):
        rows.append(
            _row(
                hours_overdue=float(max(6, rng.normal(20, 8))),
                missed_7=int(rng.integers(2, 6)),
                missed_14=int(rng.integers(3, 9)),
                consecutive=int(rng.integers(2, 5)),
                days_visit=float(max(8, rng.normal(16, 5))),
                hour_dev=float(abs(rng.normal(5, 2))),
            )
        )
    return rows, [0] * n_typical + [1] * n_unusual


def compare_on_synthetic():
    rows, unusual_flag = synthetic_dataset()
    X = np.array([[r[k] for k in FEATURE_ORDER] for r in rows], dtype=float)
    forest = IsolationForest(random_state=7, contamination=0.2)
    forest.fit(X)
    pred = forest.predict(X)  # -1 unusual, 1 typical
    forest_unusual = (pred == -1).astype(int)

    rule_high = []
    for r in rows:
        score, priority, _ = score_from_features(r)
        rule_high.append(1 if priority in ("high", "critical") else 0)

    def agree(a, b):
        return float(np.mean(np.array(a) == np.array(b)))

    return {
        "n_rows": len(rows),
        "synthetic_label": "SYNTHETIC DEMONSTRATION DATA — not real households",
        "rule_high_or_critical": int(sum(rule_high)),
        "forest_unusual": int(forest_unusual.sum()),
        "agreement_rule_vs_forest": round(agree(rule_high, forest_unusual), 3),
        "agreement_forest_vs_planted_unusual": round(agree(forest_unusual, unusual_flag), 3),
        "agreement_rule_vs_planted_unusual": round(agree(rule_high, unusual_flag), 3),
        "note": (
            "Planted 'unusual' rows are generated by the script, not observed in care. "
            "Agreement on this set is a teaching statistic only."
        ),
    }
